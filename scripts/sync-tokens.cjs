#!/usr/bin/env node
/**
 * Writes the customer-side CSS tokens from resources/design/tokens.cjs into
 * public/assets/css/styles.css, between the tokens:start / tokens:end markers
 * (appended once if the markers are missing). Run after changing tokens.cjs:
 *   node scripts/sync-tokens.cjs
 */
const fs = require('fs');
const path = require('path');
const t = require('../resources/design/tokens.cjs');

const file = path.join(__dirname, '..', 'public/assets/css/styles.css');
const START = '/* tokens:start (generated by scripts/sync-tokens.cjs from resources/design/tokens.cjs; do not edit by hand) */';
const END = '/* tokens:end */';

const css = fs.readFileSync(file, 'utf8');
const root = css.slice(css.indexOf(':root {'), css.indexOf('}', css.indexOf(':root {')));
const vars = [];
// colours the original :root block doesn't define yet
for (const [k, v] of Object.entries(t.color)) if (!root.includes(`--${k}:`)) vars.push(`  --${k}: ${v};`);
for (const [k, v] of Object.entries(t.space)) vars.push(`  --sp-${k}: ${v};`);
vars.push(`  --r-pill: ${t.radius.pill};`);
const rules = [];
for (const [prefix, map] of [['st', t.loanStatus], ['pay', t.paymentStatus]]) {
  for (const [k, [bg, fg]] of Object.entries(map)) {
    const key = k.replace(/_/g, '-');
    vars.push(`  --${prefix}-${key}-bg: var(--${bg});`, `  --${prefix}-${key}-fg: var(--${fg});`);
    rules.push(`.${prefix}-${key} {\n  background: var(--${prefix}-${key}-bg);\n  color: var(--${prefix}-${key}-fg);\n}`);
  }
}
const block = `${START}\n:root {\n${vars.join('\n')}\n}\n${rules.join('\n')}\n${END}`;

const out = css.includes(START)
  ? css.slice(0, css.indexOf(START)) + block + css.slice(css.indexOf(END) + END.length)
  : css.replace(/\s*$/, '') + '\n\n' + block + '\n';
fs.writeFileSync(file, out);
console.log('tokens written to public/assets/css/styles.css');
